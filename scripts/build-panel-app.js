// node scripts/build-panel-app.js [--check]
// The control panel's main script is written as per-page files in control-panel/app/NN-*.js and
// shipped as ONE script, control-panel/app.js, built here by joining them in file-name order.
//
// Why one script and not one <script> tag per file: code that runs while the page loads schedules
// timers and promise callbacks, and the panel's WebSocket can deliver messages early. Between two
// separate script files the browser runs those tasks, so they would see the later files' functions
// and constants missing. Inside one script they cannot run until all of it has loaded, which is
// what this code has always relied on.
//
// --check: exit 1 when control-panel/app.js is not what the parts build to (the test suite runs
// this through test/panel-bundle.test.js).
'use strict';
const fs = require('fs');
const path = require('path');

const CP = path.join(__dirname, '..', 'control-panel');
const DIR = path.join(CP, 'app');
const OUT = path.join(CP, 'app.js');

const BANNER = [
  '/* GENERATED by scripts/build-panel-app.js from control-panel/app/*.js. Do not edit this file:',
  '   edit the part, then run `node scripts/build-panel-app.js`. test/panel-bundle.test.js fails when',
  '   this file and the parts disagree. One script on purpose (see the build script). */',
  ''
].join('\n');

function parts() {
  return fs.readdirSync(DIR).filter((f) => /^\d\d-[a-z0-9-]+\.js$/.test(f)).sort();
}
function build() {
  return BANNER + parts().map((f) => fs.readFileSync(path.join(DIR, f), 'utf8').replace(/\r\n/g, '\n').replace(/\s+$/, '') + '\n').join('\n');
}

if (require.main === module) {
  const want = build();
  const have = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n') : '';
  if (process.argv.includes('--check')) {
    if (have !== want) { console.error('control-panel/app.js is out of date: run node scripts/build-panel-app.js'); process.exit(1); }
    console.log('control-panel/app.js matches its ' + parts().length + ' parts');
  } else if (have === want) {
    console.log('control-panel/app.js already up to date (' + parts().length + ' parts)');
  } else {
    fs.writeFileSync(OUT, want);
    console.log('built control-panel/app.js from ' + parts().length + ' parts');
  }
}
module.exports = { build, parts };
